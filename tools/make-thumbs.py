#!/usr/bin/env python3
"""Generate the derived files of the portfolio from batman.html and the original images.

Two sets of optimised WebP copies, derived from every relative <img src> found in batman.html (plus the profile portrait):

    pirate/thumbs/<slug>.webp   640 px wide  - used by the pirate world's cards
    batman/img/<slug>.webp      960 px wide  - used by the Batman page via <picture>/<source>

and one script that makes the pirate world work when a page is opened straight from disk (file://):

    pirate/batman-snapshot.js   batman.html as a JavaScript string. Browsers refuse fetch() of other files on file://, so
                                pirate-data.js reads this copy instead - and only when the fetch fails. Served over
                                http(s) (GitHub Pages, python -m http.server) the live batman.html is always read.

Originals are never modified; if a WebP is missing the pages fall back to the original image.

    pip install pillow
    python tools/make-thumbs.py          # run from the repository root

Add a project, or edit batman.html -> run this again -> commit pirate/thumbs/, batman/img/ and pirate/batman-snapshot.js.
The slug rule here MUST match thumbSlug() in pirate/pirate-data.js.
"""
import json
import os
import re
import sys

from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
SOURCE = os.path.join(ROOT, 'batman.html')
SNAPSHOT = os.path.join(ROOT, 'pirate', 'batman-snapshot.js')
OUTPUTS = [
    # (folder, max width, WebP quality)
    (os.path.join(ROOT, 'pirate', 'thumbs'), 640, 76),
    (os.path.join(ROOT, 'batman', 'img'), 960, 80),
]
EXTRA = ['sps.png']  # profile portrait: hero of the Batman page, Captain's Log of the pirate world


def slug(path):
    base = os.path.splitext(os.path.basename(path))[0].lower()
    return re.sub(r'[^a-z0-9]+', '-', base).strip('-')


def write_snapshot(html):
    """batman.html as a JS string for pages opened from disk (see the module docstring). ASCII-only on purpose: a file://
    page has no HTTP header to say which charset a script uses, and \\uXXXX escapes make that irrelevant."""
    payload = json.dumps(html, ensure_ascii=True)
    with open(SNAPSHOT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/*! Generated by tools/make-thumbs.py from batman.html - do not edit by hand.\n'
                ' * pirate-data.js loads this ONLY when fetch("batman.html") is blocked (a page opened straight from disk, file://),\n'
                ' * so the pirate world still shows every project. Re-run the tool after editing batman.html. */\n')
        f.write('window.__BATMAN_SNAPSHOT__ = ' + payload + ';\n')
    return os.path.getsize(SNAPSHOT)


def main():
    html = open(SOURCE, encoding='utf-8', errors='replace').read()
    snap = write_snapshot(html)
    print(f'pirate/batman-snapshot.js  {snap / 1024:.0f} KB  (batman.html for pages opened from disk)\n')
    srcs = re.findall(r'<img\b[^>]*?\bsrc="([^"]+)"', html)
    wanted = []
    for s in srcs + EXTRA:
        if re.match(r'^(https?:)?//', s) or s.startswith('data:'):
            continue
        s = s.split('?')[0].lstrip('./')
        if s.lower().endswith('.gif') or s in wanted:
            continue
        wanted.append(s)

    for folder, _, _ in OUTPUTS:
        os.makedirs(folder, exist_ok=True)
    seen, total_in = {}, 0
    total_out = [0] * len(OUTPUTS)
    print(f'{"image":<30}{"original":>10}' + ''.join(f'{os.path.basename(f) + " " + str(w) + "px":>18}' for f, w, _ in OUTPUTS))
    for rel in wanted:
        src = os.path.join(ROOT, rel)
        if not os.path.isfile(src):
            print(f'  skip (missing on disk): {rel}')
            continue
        name = slug(rel)
        if name in seen and seen[name] != rel:
            sys.exit(f'slug collision: {rel} and {seen[name]} -> {name}')
        seen[name] = rel
        sizes = []
        with Image.open(src) as im0:
            im0 = im0.convert('RGBA' if im0.mode in ('RGBA', 'LA', 'P') else 'RGB')
            for i, (folder, max_w, quality) in enumerate(OUTPUTS):
                im = im0
                if im.width > max_w:
                    im = im.resize((max_w, round(im.height * max_w / im.width)), Image.LANCZOS)
                dst = os.path.join(folder, name + '.webp')
                im.save(dst, 'WEBP', quality=quality, method=6)
                sizes.append(os.path.getsize(dst))
                total_out[i] += sizes[-1]
        orig = os.path.getsize(src)
        total_in += orig
        print(f'  {rel:<28}{orig / 1024:8.0f}KB' + ''.join(f'{s / 1024:16.0f}KB' for s in sizes))
    print(f'\n{len(seen)} images: {total_in / 1048576:.1f} MB original -> ' +
          ', '.join(f'{t / 1048576:.2f} MB ({os.path.basename(f)})' for t, (f, _, _) in zip(total_out, OUTPUTS)))


if __name__ == '__main__':
    main()
