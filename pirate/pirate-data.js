/*!
 * pirate-data.js — turns the Batman portfolio into plain data for the pirate world.
 *
 * batman.html is the single source of truth. Rather than retyping projects, this file fetches that
 * page, parses it (DOMParser creates an inert document, so nothing in it runs or loads), and reads
 * every section — including the cards the Batman page hides behind "See More".
 * Add a project to batman.html and it appears on the pirate map automatically.
 * (Opened straight from disk, where fetch() is blocked, it reads a generated script copy instead — see load().)
 *
 * Exposes window.PirateData.load() -> Promise<model>
 */
(function (root) {
  'use strict';

  var SOURCE = 'batman.html';          // same directory as pirate.html -> works under /Portfolio-Website/
  var THUMBS = 'pirate/thumbs/';       // generated by tools/make-thumbs.py
  var SNAPSHOT = 'pirate/batman-snapshot.js';   // generated by tools/make-thumbs.py - batman.html as a script, for pages opened from disk

  /* ------------------------------------------------------------------ helpers */
  function txt(el) { return el ? el.textContent.replace(/\s+/g, ' ').trim() : ''; }

  // Batman copy leads with emoji (and has three corrupted U+FFFD glyphs). Strip them for the pirate UI.
  var EMOJI = /[\p{Extended_Pictographic}‍️�\u{1F3FB}-\u{1F3FF}]/gu;
  function clean(s) { return (s || '').replace(EMOJI, '').replace(/\s+/g, ' ').replace(/^[\s:•\-–—]+/, '').trim(); }

  function slugify(s) {
    return clean(s).toLowerCase().replace(/&/g, ' and ').replace(/['’]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
  }
  // Must match slug() in tools/make-thumbs.py
  function thumbSlug(src) {
    var base = src.split('?')[0].split('/').pop().replace(/\.[^.]+$/, '').toLowerCase();
    return base.replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
  }
  function isExternal(u) { return /^(https?:)?\/\//i.test(u) || /^data:/i.test(u); }

  /* ------------------------------------------------------------------ tech stack
   * "Technology stack, where available": only technologies the card's own text names are shown —
   * nothing is guessed. Order here = order of the chips.                                          */
  var TECH = [
    ['MERN Stack', /\bMERN\b/i], ['Next.js', /\bnext\.?js\b/i], ['TypeScript', /\btypescript\b/i],
    ['Supabase', /\bsupabase\b/i], ['PHP', /\bphp\b/i], ['MySQL', /\bmysql\b/i],
    ['Python', /\bpython\b/i], ['PyOpenGL', /\bpyopengl\b/i], ['OpenGL', /\bopengl\b/i], ['PyQt5', /\bpyqt5\b/i],
    ['NumPy', /\bnumpy\b/i], ['SciPy', /\bscipy\b/i], ['Matplotlib', /\bmatplotlib\b/i],
    ['Machine Learning', /machine learning/i], ['OOP', /object-oriented/i],
    ['Arduino Uno', /arduino uno/i], ['Arduino', /arduino(?! uno)/i],
    ['Ultrasonic sensor', /ultrasonic/i], ['IR sensor', /\bIR\b/], ['KY-038', /ky-038/i],
    ['Op-amps', /op-?amps?/i], ['Schmitt trigger', /schmitt/i], ['Wien bridge oscillator', /wien bridge/i],
    ['Cisco Packet Tracer', /packet tracer/i], ['VLSM', /\bVLSM\b/], ['RIPv2', /RIPv2/i], ['DHCP', /\bDHCP\b/], ['DNS', /\bDNS\b/],
    ['x86 Assembly', /x86 assembly/i], ['YouTube Data API', /youtube data api/i],
    ['Google Sheets', /google sheets/i], ['Google Forms', /google form/i], ['CSV', /\bcsv\b/i],
    ['Midpoint Line Algorithm', /midpoint line/i], ['Static website', /static website/i]
  ];
  function techOf(text) {
    var out = [];
    TECH.forEach(function (t) { if (t[1].test(text)) out.push(t[0]); });
    return out;
  }
  // Used by the Treasure Islands filter. Anything not matched here counts as software.
  var HARDWARE = /arduino|circuit|op-?amp|sensor|robot/i;

  /* ------------------------------------------------------------------ extraction */
  function parse(doc, baseUrl) {
    function q(sel, root) { return (root || doc).querySelector(sel); }
    function qa(sel, root) { return Array.prototype.slice.call((root || doc).querySelectorAll(sel)); }
    function abs(u) {
      if (!u || u.charAt(0) === '#') return u || '';
      if (/^(mailto|tel):/i.test(u)) return u;
      try { return new URL(u, baseUrl).href; } catch (e) { return u; }
    }
    function imgInfo(img) {
      if (!img) return null;
      var raw = img.getAttribute('src') || '';
      return {
        full: isExternal(raw) ? raw : abs(raw),
        thumb: isExternal(raw) ? raw : THUMBS + thumbSlug(raw) + '.webp',
        alt: img.getAttribute('alt') || ''
      };
    }
    function linkInfo(a) {
      var href = a.getAttribute('href') || '';
      var label = clean(txt(a));
      var kind = /demo|try it|site/i.test(label) ? 'live'
               : /certificate/i.test(label) ? 'cert'
               : /playlist/i.test(label) ? 'playlist'
               : /blog/i.test(label) ? 'blog'
               : /study|analysis|read/i.test(label) ? 'read'
               : 'code';
      // open in a new tab exactly when the Batman page does (external URLs, and files such as pbl.html)
      return { label: label, href: abs(href), kind: kind, newTab: a.getAttribute('target') === '_blank' || isExternal(href) };
    }
    var used = {};
    function uniqueSlug(section, base) {          // stable, URL-safe id; unique within a section
      var s = base || 'item', n = 2;
      while (used[section + ':' + s]) s = base + '-' + n++;
      used[section + ':' + s] = true;
      return s;
    }
    function card(el, section) {
      var title = clean(txt(q('h4', el)));
      var desc = txt(q('p', el));
      var meta = {};
      try { meta = JSON.parse(el.getAttribute('data-project') || '{}'); } catch (e) { /* ignore */ }
      var item = {
        slug: uniqueSlug(section, slugify(title)),
        title: title,
        desc: desc,
        summary: meta.desc || desc,
        image: imgInfo(q('img', el)),
        links: qa('a.btn', el).map(linkInfo),
        hasPreview: !!q('.preview-btn', el),
        tech: techOf(title + ' ' + desc)
      };
      item.hardware = HARDWARE.test(title + ' ' + desc);
      return item;
    }
    function cards(sel, section) { return qa(sel, doc).map(function (c) { return card(c, section); }); }

    /* ---- profile (Captain's Log) ---- */
    var heroName = txt(q('.hero h2 strong')) || 'Shiva Prasad Sarkar';
    var heroLinks = qa('.hero .cta-row a').map(linkInfo).map(function (l) {
      l.kind = /cv/i.test(l.label) ? 'cv' : /channel/i.test(l.label) ? 'youtube' : 'github';
      l.label = /cv/i.test(l.label) ? 'CV' : /channel/i.test(l.label) ? 'YouTube channel' : 'GitHub';
      return l;
    });
    var cvCard = q('#cv .cv-card');

    /* ---- contact ---- */
    var contactGroups = qa('#connect .social-category').map(function (g) {
      var links = qa('a.pill', g).map(function (a) {
        var img = q('img', a);
        return { name: img ? img.getAttribute('alt') : clean(txt(a)), href: abs(a.getAttribute('href')) };
      });
      var names = links.map(function (l) { return l.name; }).join(' ');
      var title = /github|linkedin/i.test(names) ? 'Professional'
                : /leetcode|codeforces|hackerrank/i.test(names) ? 'Competitive programming'
                : 'Social & email';
      return { title: title, links: links };
    });
    var info = qa('#connect .contact-info p').map(function (p) {
      var label = clean(txt(q('strong', p))).replace(/:$/, '');
      var a = q('a', p);
      var value = clean(txt(p).replace(txt(q('strong', p)), ''));
      var map = { 'Secure Line': 'Email', 'Dossier': 'CV (second copy)', 'Territory': 'Location', 'Training Ground': 'University' };
      return { label: map[label] || label, value: value, href: a ? abs(a.getAttribute('href')) : '' };
    });
    var mail = q('#connect a[href^="mailto:"]');

    return {
      profile: {
        name: heroName,
        affiliation: txt(q('.brand p')),
        avatar: imgInfo(q('.hero .avatar')),
        stats: qa('.hero .stat').map(function (s) { return { value: txt(q('h3', s)), label: txt(q('p', s)) }; }),
        links: heroLinks
      },
      skills: qa('#skills .skill-category').map(function (c) {
        return {
          title: clean(txt(q('.skill-category-title', c))),
          items: qa('img', c).map(function (i) { return i.getAttribute('alt') || ''; }).filter(Boolean)
        };
      }),
      arena: {
        platforms: qa('#problem-solving .platform-link').map(function (a) {
          return { name: clean(txt(a)), href: abs(a.getAttribute('href')) };
        }),
        stats: qa('#problem-solving .stat-card a').map(function (a) {
          var img = q('img', a);
          return { href: abs(a.getAttribute('href')), src: img ? img.getAttribute('src') : '', alt: img ? img.getAttribute('alt') : '' };
        })
      },
      projects: cards('#projects-grid .card', 'p'),
      games: cards('#mygames-grid .card', 'g'),
      certificates: cards('#certificates-grid .card', 'c'),
      research: cards('#research .card', 'r'),
      blogs: cards('#blogs-grid .card', 'b'),
      videos: cards('#videos .card', 'v'),
      cv: {
        about: txt(q('.cv-info > p', cvCard)),
        highlights: qa('.cv-highlights li', cvCard).map(function (li) { return clean(txt(li)); }),
        download: (function () { var a = q('.btn-primary', cvCard); return a ? linkInfo(a) : null; })()
      },
      contact: {
        email: mail ? mail.getAttribute('href').replace(/^mailto:/i, '') : '',
        groups: contactGroups,
        info: info
      }
    };
  }

  /* ------------------------------------------------------------------ load
   * Two ways to get batman.html's markup:
   *   1. fetch() it - always the live page. This is what runs on GitHub Pages and any http(s) server.
   *   2. a script copy (pirate/batman-snapshot.js, written by tools/make-thumbs.py). A page opened straight from disk
   *      (file://) is not allowed to fetch() other files, but it may load scripts - so the same markup ships as one.
   *      It is only requested when needed: first choice on file://, fallback when a fetch fails anywhere else.
   * Either way the markup goes through the same parser, so the model is identical.                                    */
  var pending = null;
  function fetchSource(base) {
    return fetch(base.href, { credentials: 'same-origin' }).then(function (r) {
      if (!r.ok) throw new Error('HTTP ' + r.status + ' for ' + SOURCE);
      return r.text();
    });
  }
  function snapshotSource() {
    if (typeof root.__BATMAN_SNAPSHOT__ === 'string') return Promise.resolve(root.__BATMAN_SNAPSHOT__);
    return new Promise(function (resolve, reject) {
      var s = document.createElement('script');
      s.async = true;
      s.src = new URL(SNAPSHOT, document.baseURI).href;
      s.onload = function () {
        if (typeof root.__BATMAN_SNAPSHOT__ === 'string') resolve(root.__BATMAN_SNAPSHOT__); else reject(new Error(SNAPSHOT + ' is empty'));
      };
      s.onerror = function () { reject(new Error('could not load ' + SNAPSHOT)); };
      document.head.appendChild(s);
    });
  }
  function load() {
    if (pending) return pending;
    var base = new URL(SOURCE, document.baseURI);
    var fromDisk = root.location && root.location.protocol === 'file:';
    var viaFetch = function () { return fetchSource(base); };
    pending = Promise.resolve()
      .then(fromDisk ? snapshotSource : viaFetch)
      .catch(fromDisk ? viaFetch : snapshotSource)
      .then(function (html) { return parse(new DOMParser().parseFromString(html, 'text/html'), base.href); });
    pending.catch(function () { pending = null; });     // allow a retry after a failure
    return pending;
  }

  root.PirateData = { load: load, slugify: slugify, thumbSlug: thumbSlug, _parse: parse };
})(window);
